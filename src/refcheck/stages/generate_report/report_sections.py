"""V1 report sections: executive summary, findings, methodology."""

import logging
from typing import TYPE_CHECKING

from refcheck.models.claim import Claim
from refcheck.models.reference import Reference
from refcheck.models.verification import VerificationResult
from refcheck.stages.generate_report.finding_detail import add_finding_detail
from refcheck.stages.generate_report.report_style import (
    AMBER,
    GRAY,
    GREEN,
    RED,
    VIOLET,
    add_colored_line,
)
from refcheck.stages.generate_report.result_signals import check_first, numbers_not_found

if TYPE_CHECKING:
    from docx.document import Document as DocxDocument

logger = logging.getLogger(__name__)


def add_executive_summary(
    doc: "DocxDocument",
    verifications: list[VerificationResult],
) -> None:
    """Add executive summary with color-coded verdict counts."""
    doc.add_heading("Executive Summary", level=2)

    counts = _count_verdicts(verifications)
    total = len(verifications)

    doc.add_paragraph(f"Total claim-reference pairs verified: {total}")
    add_colored_line(doc, f"Supported: {counts['supported']}", GREEN)
    add_colored_line(doc, f"Partially supported: {counts['partially_supported']}", AMBER)
    add_colored_line(doc, f"Not supported: {counts['not_supported']}", RED)
    add_colored_line(doc, f"Contradicted: {counts['contradicted']}", RED)
    add_colored_line(doc, f"Cannot verify: {counts['cannot_verify']}", GRAY)
    if counts.get("not_relevant", 0) > 0:
        add_colored_line(doc, f"Not relevant: {counts['not_relevant']}", VIOLET)
    disputed = sum(1 for v in verifications if v.consensus_type == "disputed")
    if disputed:
        add_colored_line(doc, f"Disputed between the two models (both views shown below, "
                              f"pending human review): {disputed}", AMBER)


def add_critical_findings(
    doc: "DocxDocument",
    verifications: list[VerificationResult],
    claims_by_id: dict[int, Claim],
) -> None:
    """Add critical findings (contradicted / not supported verdicts)."""
    critical = [
        v for v in verifications
        if v.verdict in ("not_supported", "contradicted")
    ]
    if not critical:
        return

    doc.add_heading("Critical Findings", level=2)
    doc.add_paragraph(
        f"{len(critical)} claim(s) flagged as problematic:"
    )

    for v in critical:
        add_finding_detail(doc, v, claims_by_id)


def add_check_first_findings(
    doc: "DocxDocument",
    verifications: list[VerificationResult],
    claims_by_id: dict[int, Claim],
) -> None:
    """Verdicts that may hide a real problem (result_signals.check_first: disputed or
    unconfirmed partials, and V5.7 triaged supported verdicts), listed right after the
    critical findings; missing figures first."""
    flagged = sorted((v for v in verifications if check_first(v)),
                     key=lambda v: not numbers_not_found(v.reasoning))
    if not flagged:
        return
    doc.add_heading("Check First: Disputed or Unconfirmed Details", level=2)
    doc.add_paragraph(
        f"{len(flagged)} claim(s) may hide a real problem: a partial verdict the verifier "
        "found unsupported (an independent model disagreed) or with figures absent from the "
        "source, or a supported verdict the triage flagged (low screen score, only secondary "
        "or future-work quotes, a cleared slot check, an overturned first run without a "
        "supporting quote). Review these first.")
    for v in flagged:
        add_finding_detail(doc, v, claims_by_id)


def add_verified_section(
    doc: "DocxDocument",
    verifications: list[VerificationResult],
) -> None:
    """Add brief section for all supported verdicts."""
    supported = [v for v in verifications if v.verdict == "supported"]
    if not supported:
        return

    doc.add_heading("Verified References", level=2)
    doc.add_paragraph(
        f"{len(supported)} claims verified as supported by their cited sources."
    )


def add_methodology_note(doc: "DocxDocument", total: int,
                         degraded: list[str] | None = None) -> None:
    """Add the methodology note; ``degraded`` lists roles that ran degraded (V5.8 G1)."""
    doc.add_heading("Methodology Note", level=2)
    doc.add_paragraph(
        "This report was generated by RefCheck AI's V5.2 verification cascade. "
        "Each claim is checked against passages retrieved from the cited paper "
        "(never the whole paper): a fast decision model screens every pair, a "
        "verifier model judges it and quotes the source verbatim (quotes are "
        "checked against the text), and every negative or unusual verdict is "
        "re-checked blind by a model from a different family. In a sentence that "
        "cites several references each reference is judged only on the part it is "
        "cited for. Disagreements are marked 'disputed', shown one severity step "
        "toward the cross-check (a not-supported call the cross-check found support "
        "for is shown as partially supported) with both views, and queued for human "
        "review. Since V5.4 every partial verdict is filed under one type (the most "
        "serious problem found) with a suggested fix, and concerns cleared by a benign "
        "check (co-cited reference, wording only, author framing, evidence re-check) are "
        "reported as supported with a note."
    )
    if degraded:
        _add_degraded_note(doc, degraded)
    doc.add_paragraph(f"Total claim-reference pairs analyzed: {total}")
    doc.add_paragraph(
        "Confidence scores are the models' own estimates, capped for abstract-only "
        "sources and disputed verdicts; they are not calibrated probabilities. "
        "Treat every flagged citation as a prompt for a human check."
    )


def _add_degraded_note(doc: "DocxDocument", degraded: list[str]) -> None:
    """Say which model roles ran degraded in this run, why, and what fixes it."""
    doc.add_heading("Degraded mode", level=3)
    doc.add_paragraph(
        "Some model roles were unavailable during this run (for example a provider "
        "account without credits), so the run continued in a reduced mode. Where the "
        "cross-check ran on the same model family as the verifier, the 'different "
        "family' re-check described above did not apply, and its confirmations were "
        "queued for human review.")
    for line in degraded:
        doc.add_paragraph(line, style="List Bullet")


def _count_verdicts(verifications: list[VerificationResult]) -> dict[str, int]:
    """Count verdicts by type."""
    counts: dict[str, int] = {
        "supported": 0, "partially_supported": 0,
        "not_supported": 0, "contradicted": 0,
        "cannot_verify": 0, "not_relevant": 0,
    }
    for v in verifications:
        if v.verdict in counts:
            counts[v.verdict] += 1
    return counts


def add_retraction_section(
    doc: "DocxDocument",
    references: list[Reference],
) -> None:
    """Add retraction warning section if any references are retracted/corrected."""
    flagged = [
        r for r in references
        if r.retraction_status not in ("ok", "unknown")
    ]
    if not flagged:
        return
    doc.add_heading("RETRACTED OR CORRECTED REFERENCES", level=2)
    para = doc.add_paragraph()
    run = para.add_run(f"WARNING: {len(flagged)} reference(s) have been flagged:")
    run.bold = True
    run.font.color.rgb = RED
    for ref in flagged:
        status = ref.retraction_status.upper().replace("_", " ")
        doc.add_paragraph(
            f"[{ref.id}] {ref.title}: {status} — {ref.retraction_detail}",
            style="List Bullet",
        )
